export const LATEST_UPDATE_ID = UPDATES[0]?.id ?? "";

const SEEN_KEY = "eo-updates-seen";
/** この端末で最後に見たお知らせの id（読めないときは空） */
export function getSeenUpdateId(): string {
  try {
    return window.localStorage.getItem(SEEN_KEY) ?? "";
  } catch {
    return "";
  }
}
/** 最新のお知らせを見たことにする（メニューの NEW を消す） */
export function markUpdatesSeen() {
  try {
    window.localStorage.setItem(SEEN_KEY, LATEST_UPDATE_ID);
  } catch {
    // 保存できない環境では、毎回 NEW が出るだけ
  }
  window.dispatchEvent(new Event("eo-updates-seen"));
}
/** まだ見ていないお知らせ（新しい順） */
export function unseenUpdates(seenId: string): UpdateNote[] {
  const i = UPDATES.findIndex((u) => u.id === seenId);
  return i < 0 ? UPDATES : UPDATES.slice(0, i);
}
